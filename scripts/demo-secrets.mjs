#!/usr/bin/env node
/**
 * Generates throwaway credentials for the local demo stack. The values land in `.env` (mode 0600),
 * which docker compose reads automatically. They are never committed.
 */
import { createHmac, randomBytes } from 'node:crypto';
import { chmodSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, '.env');

const base64url = (value) => Buffer.from(value).toString('base64url');
const jwtSecret = randomBytes(48).toString('base64url');
const postgresPassword = randomBytes(24).toString('base64url');

function token(role) {
  const header = base64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }));
  const payload = base64url(
    JSON.stringify({
      role,
      iss: 'authkit-demo',
      iat: Math.floor(Date.now() / 1000),
      exp: Math.floor(Date.now() / 1000) + 60 * 60 * 24 * 30,
    }),
  );
  const signature = createHmac('sha256', jwtSecret).update(`${header}.${payload}`).digest('base64url');
  return `${header}.${payload}.${signature}`;
}

writeFileSync(
  output,
  [
    '# Generated by scripts/demo-secrets.mjs for a local run. Never commit this file.',
    `JWT_SECRET=${jwtSecret}`,
    `POSTGRES_PASSWORD=${postgresPassword}`,
    `ANON_KEY=${token('anon')}`,
    '',
  ].join('\n'),
  { mode: 0o600 },
);
chmodSync(output, 0o600);

console.log('demo-secrets: wrote .env (0600) with a per-run JWT secret and anon key.');
